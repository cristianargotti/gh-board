var (
	emDash = string(rune(0x2014))
	enDash = string(rune(0x2013))
)

func TestDashViolations(t *testing.T) {
	data := []byte("clean\nwith " + emDash + " em\nwith " + enDash + " en\n")
	got := dashViolations("docs/a.md", data)
	if len(got) != 2 || got[0] != "docs/a.md:2: em dash" || got[1] != "docs/a.md:3: en dash" {
		t.Fatalf("got %v", got)
	}
	if len(dashViolations("x", []byte("plain - hyphen"))) != 0 {
		t.Fatal("hyphens are allowed")
	}
}

func longFunc(lines int) string {
	var b strings.Builder
	b.WriteString("package p\n\nfunc long() {\n")
	for i := 0; i < lines-2; i++ {
		b.WriteString("\t_ = 1\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func TestLengthViolations(t *testing.T) {
	short := []byte("package p\n\nfunc ok() {}\n\nfunc none()\n")
	if got := lengthViolations("a.go", short); len(got) != 0 {
		t.Fatalf("short file flagged: %v", got)
	}
	if got := lengthViolations("b.go", []byte(longFunc(41))); len(got) != 1 || !strings.Contains(got[0], "function long is 41 lines") {
		t.Fatalf("41-line function: %v", got)
	}
	if got := lengthViolations("c.go", []byte(longFunc(40))); len(got) != 0 {
		t.Fatalf("40-line function flagged: %v", got)
	}
	big := "package p\n" + strings.Repeat("// c\n", 300)
	if got := lengthViolations("d.go", []byte(big)); len(got) != 1 || !strings.Contains(got[0], "301 lines") {
		t.Fatalf("301-line file: %v", got)
	}
	if got := lengthViolations("e.go", []byte("package p\n\nfunc {")); len(got) != 1 || !strings.Contains(got[0], "parse error") {
		t.Fatalf("parse error: %v", got)
	}
	if countLines([]byte("")) != 0 || countLines([]byte("a")) != 1 || countLines([]byte("a\nb\n")) != 2 {
		t.Fatal("countLines is wrong")
	}
}

