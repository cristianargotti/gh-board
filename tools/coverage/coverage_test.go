const module = "example.com/m"

const sampleProfile = `mode: atomic
example.com/m/a/a.go:5.13,7.2 2 1
example.com/m/a/a.go:9.13,11.2 3 0
example.com/m/a/a.go:9.13,11.2 3 4
example.com/m/b/b.go:3.13,4.2 1 1
`

func TestParseProfile(t *testing.T) {
	files, err := parseProfile(strings.NewReader(sampleProfile))
	if err != nil {
		t.Fatal(err)
	}
	stmts, covered := files["example.com/m/a/a.go"].totals()
	if stmts != 5 || covered != 5 {
		t.Fatalf("a.go = %d/%d, duplicate blocks must merge as covered", covered, stmts)
	}
	if stmts, covered := files["example.com/m/b/b.go"].totals(); stmts != 1 || covered != 1 {
		t.Fatalf("b.go = %d/%d", covered, stmts)
	}
	for _, bad := range []string{"x.go:1.1,2.2 1", "x.go 1 1", "x.go:1.1,2.2 a 1", "x.go:1.1,2.2 1 b"} {
		if _, err := parseProfile(strings.NewReader("mode: set\n" + bad + "\n")); err == nil {
			t.Errorf("%q must fail", bad)
		}
	}
}

func TestEvaluate(t *testing.T) {
	files, _ := parseProfile(strings.NewReader(sampleProfile))
	sources := []string{"example.com/m/a/a.go", "example.com/m/b/b.go", "example.com/m/c/c.go"}
	rep := evaluate(files, sources, 80)
	if len(rep.Failures) != 2 {
		t.Fatalf("failures = %v", rep.Failures)
	}
	if !strings.Contains(rep.Failures[0], "package example.com/m/c 0.0%") || !strings.Contains(rep.Failures[1], "file example.com/m/c/c.go 0.0%") {
		t.Fatalf("failures = %v", rep.Failures)
	}
	text := rep.String()
	if !strings.Contains(text, "100.0%") || !strings.Contains(text, "FAIL file example.com/m/c/c.go") {
		t.Fatalf("report = %s", text)
	}
	if (tally{}).percent() != 0 || (tally{stmts: 4, covered: 1}).percent() != 25 {
		t.Fatal("percent is wrong")
	}
}

func writeFixture(t *testing.T, root, rel, content string) {
	t.Helper()
	path := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func fixtureModule(t *testing.T) string {
	root := t.TempDir()
	writeFixture(t, root, "go.mod", "module "+module+"\n\ngo 1.27\n")
	writeFixture(t, root, "a/a.go", "package a\n\nfunc A() int { return 1 }\n")
	writeFixture(t, root, "a/a_test.go", "package a\n")
	writeFixture(t, root, "b/b.go", "package b\n\nfunc B() int { return 1 }\n")
	writeFixture(t, root, "types/t.go", "package types\n\ntype T struct{}\n\nfunc (T) Empty() {}\n")
	writeFixture(t, root, "gen/g.go", "// Code generated by x. DO NOT EDIT.\npackage gen\n\nfunc G() int { return 1 }\n")
	writeFixture(t, root, "testdata/x.go", "package x\n\nfunc X() int { return 1 }\n")
	return root
}

func TestSourceFiles(t *testing.T) {
	root := fixtureModule(t)
	mod, err := modulePath(root)
	if err != nil || mod != module {
		t.Fatalf("modulePath = %q, %v", mod, err)
	}
	got, err := sourceFiles(root, mod)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{module + "/a/a.go", module + "/b/b.go"}
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Fatalf("sourceFiles = %v, want %v", got, want)
	}
	writeFixture(t, root, "bad/bad.go", "package {")
	if _, err := sourceFiles(root, mod); err == nil {
		t.Fatal("a file that does not parse must fail")
	}
}

func TestModulePathErrors(t *testing.T) {
	root := t.TempDir()
	if _, err := modulePath(root); err == nil {
		t.Fatal("missing go.mod must fail")
	}
	writeFixture(t, root, "go.mod", "go 1.27\n")
	if _, err := modulePath(root); err == nil {
		t.Fatal("go.mod without module line must fail")
	}
}

func TestRun(t *testing.T) {
	root := fixtureModule(t)
	profile := filepath.Join(root, "coverage.out")
	writeFixture(t, root, "coverage.out", "mode: atomic\n"+module+"/a/a.go:3.13,3.26 1 1\n")
	rep, err := run(profile, root, 80)
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.Failures) != 2 || !strings.Contains(rep.Failures[1], "b/b.go") {
		t.Fatalf("failures = %v", rep.Failures)
	}
	if _, err := run(filepath.Join(root, "missing.out"), root, 80); err == nil {
		t.Fatal("missing profile must fail")
	}
	writeFixture(t, root, "bad.out", "mode: atomic\nbroken\n")
	if _, err := run(filepath.Join(root, "bad.out"), root, 80); err == nil {
		t.Fatal("malformed profile must fail")
	}
	if _, err := run(profile, t.TempDir(), 80); err == nil {
		t.Fatal("root without go.mod must fail")
	}
}

func TestExecute(t *testing.T) {
	root := fixtureModule(t)
	full := "mode: atomic\n" + module + "/a/a.go:3.13,3.26 1 1\n" + module + "/b/b.go:3.13,3.26 1 1\n"
	writeFixture(t, root, "full.out", full)
	writeFixture(t, root, "partial.out", "mode: atomic\n"+module+"/a/a.go:3.13,3.26 1 1\n")
	var out, errOut strings.Builder
	args := []string{"-profile", filepath.Join(root, "full.out"), "-root", root, "-min", "80"}
	if code := execute(args, &out, &errOut); code != 0 || !strings.Contains(out.String(), "100.0%") {
		t.Fatalf("full: code %d, out %q, err %q", code, out.String(), errOut.String())
	}
	args[1] = filepath.Join(root, "partial.out")
	if code := execute(args, &out, &errOut); code != 1 || !strings.Contains(errOut.String(), "below 80%") {
		t.Fatalf("partial: code %d, err %q", code, errOut.String())
	}
	args[1] = filepath.Join(root, "missing.out")
	if code := execute(args, &out, &errOut); code != 2 {
		t.Fatalf("missing: code %d", code)
	}
	if code := execute([]string{"-bogus"}, &out, &errOut); code != 2 {
		t.Fatalf("bad flag: code %d", code)
	}
}

// A file that the build constraints leave out on this operating system is
// covered where it is compiled, so it is not a source here.
func TestSourceFilesHonorBuildConstraints(t *testing.T) {
	root := fixtureModule(t)
	tag := "windows"
	if runtime.GOOS == tag {
		tag = "linux"
	}
	writeFixture(t, root, "os/other.go", "//go:build "+tag+"\n\npackage os\n\nfunc Other() int { return 1 }\n")
	writeFixture(t, root, "os/here.go", "package os\n\nfunc Here() int { return 1 }\n")
	got, err := sourceFiles(root, module)
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(got, ",")
	if strings.Contains(joined, "os/other.go") || !strings.Contains(joined, "os/here.go") {
		t.Fatalf("sourceFiles = %v", got)
	}
}
